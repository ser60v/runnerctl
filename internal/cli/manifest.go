const poolAPIVersion = "runner.retardsoftware.com/v1"

type poolSpec struct {
	Name          string `json:"name" yaml:"name"`
	Environment   string `json:"environment" yaml:"environment"`
	SiteID        string `json:"site_id" yaml:"site_id"`
	CPU           int    `json:"cpu_millis" yaml:"cpu_millis"`
	Memory        int    `json:"memory_mib" yaml:"-"`
	Disk          int    `json:"disk_mib" yaml:"-"`
	MaxJobMinutes int    `json:"max_job_minutes" yaml:"max_job_minutes"`
	MaxRunners    int    `json:"max_runners" yaml:"max_runners"`
	Enabled       *bool  `json:"enabled" yaml:"enabled"`
}

type poolSpecYAML struct {
	Name          string `yaml:"name"`
	Environment   string `yaml:"environment"`
	SiteID        string `yaml:"site_id"`
	CPU           int    `yaml:"cpu_millis"`
	Memory        string `yaml:"memory"`
	Disk          string `yaml:"disk"`
	MaxJobMinutes int    `yaml:"max_job_minutes"`
	MaxRunners    int    `yaml:"max_runners"`
	Enabled       *bool  `yaml:"enabled"`
}

func (s poolSpec) MarshalYAML() (any, error) {
	return poolSpecYAML{s.Name, s.Environment, s.SiteID, s.CPU, formatSize(s.Memory), formatSize(s.Disk), s.MaxJobMinutes, s.MaxRunners, s.Enabled}, nil
}

func (s *poolSpec) UnmarshalYAML(node *yaml.Node) error {
	if node.Kind != yaml.MappingNode {
		return errors.New("spec must be a mapping")
	}
	var memoryNode, diskNode *yaml.Node
	valid := map[string]bool{"name": true, "environment": true, "site_id": true, "cpu_millis": true, "memory": true, "disk": true, "memory_mib": true, "disk_mib": true, "max_job_minutes": true, "max_runners": true, "enabled": true}
	for i := 0; i < len(node.Content); i += 2 {
		key, value := node.Content[i].Value, node.Content[i+1]
		if !valid[key] {
			return fmt.Errorf("unknown spec field %q", key)
		}
		switch key {
		case "memory", "memory_mib":
			if memoryNode != nil {
				return errors.New("spec.memory and spec.memory_mib cannot both be supplied")
			}
			memoryNode = value
		case "disk", "disk_mib":
			if diskNode != nil {
				return errors.New("spec.disk and spec.disk_mib cannot both be supplied")
			}
			diskNode = value
		}
	}
	var raw struct {
		Name          string `yaml:"name"`
		Environment   string `yaml:"environment"`
		SiteID        string `yaml:"site_id"`
		CPU           int    `yaml:"cpu_millis"`
		MaxJobMinutes int    `yaml:"max_job_minutes"`
		MaxRunners    int    `yaml:"max_runners"`
		Enabled       *bool  `yaml:"enabled"`
	}
	if err := node.Decode(&raw); err != nil {
		return err
	}
	*s = poolSpec{Name: raw.Name, Environment: raw.Environment, SiteID: raw.SiteID, CPU: raw.CPU, MaxJobMinutes: raw.MaxJobMinutes, MaxRunners: raw.MaxRunners, Enabled: raw.Enabled}
	var err error
	if s.Memory, err = sizeFromYAML(memoryNode); err != nil {
		return fmt.Errorf("spec.memory: %w", err)
	}
	if s.Disk, err = sizeFromYAML(diskNode); err != nil {
		return fmt.Errorf("spec.disk: %w", err)
	}
	return nil
}

func sizeFromYAML(node *yaml.Node) (int, error) {
	if node == nil {
		return 0, errors.New("missing size")
	}
	if node.Kind != yaml.ScalarNode || (node.Tag != "!!str" && node.Tag != "!!int") {
		return 0, errors.New("size must be a string with units or an integer MiB value")
	}
	if node.Tag == "!!int" {
		var value int
		if err := node.Decode(&value); err != nil {
			return 0, err
		}
		if value <= 0 {
			return 0, errors.New("size must be positive")
		}
		return value, nil
	}
	return parseSize(node.Value)
}

type manifest struct {
	APIVersion string `yaml:"apiVersion"`
	Kind       string `yaml:"kind"`
	Context    string `yaml:"context"`
	Metadata   struct {
		ID             string `yaml:"id"`
		OrganizationID string `yaml:"organization_id"`
		ProjectID      string `yaml:"project_id"`
	} `yaml:"metadata"`
	Spec poolSpec `yaml:"spec"`
}

func readManifest(path string) (manifest, error) {
	var m manifest
	f, err := os.Open(path)
	if err != nil {
		return m, err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, 1024*1024+1))
	if err != nil {
		return m, err
	}
	if len(data) > 1024*1024 {
		return m, errors.New("manifest exceeds 1 MiB")
	}
	var tree yaml.Node
	if err := yaml.Unmarshal(data, &tree); err != nil {
		return m, errors.New("invalid YAML")
	}
	if err := validateYAML(&tree); err != nil {
		return m, err
	}
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&m); err != nil {
		return m, fmt.Errorf("invalid pool manifest: %w", err)
	}
	var extra any
	if dec.Decode(&extra) != io.EOF {
		return m, errors.New("exactly one YAML document is required")
	}
	// Keep manifests generated by runnerctl before 0.1.4 compatible.
	if (m.APIVersion != poolAPIVersion && m.APIVersion != "runner.ser60v.com/v1") || m.Kind != "Pool" {
		return m, fmt.Errorf("expected apiVersion %s and kind Pool", poolAPIVersion)
	}
	if !contextName.MatchString(m.Context) {
		return m, errors.New("manifest context must name an existing CLI context")
	}
	for key, value := range map[string]string{"metadata.id": m.Metadata.ID, "metadata.organization_id": m.Metadata.OrganizationID, "metadata.project_id": m.Metadata.ProjectID} {
		if err := validateUUID(key, value); err != nil {
			return m, err
		}
	}
	if m.Spec.SiteID != "" {
		if !sitePattern.MatchString(m.Spec.SiteID) {
			return m, errors.New("spec.site_id must be a site identifier from sites list")
		}
	}
	if m.Spec.Enabled == nil || m.Spec.Name == "" || m.Spec.Environment == "" || m.Spec.CPU < 500 || m.Spec.Memory < 512 || m.Spec.Disk < 512 || m.Spec.MaxRunners < 1 || m.Spec.MaxJobMinutes < 1 {
		return m, errors.New("spec requires name, environment, resources, max_runners, max_job_minutes and explicit enabled")
	}
	return m, nil
}

func validateYAML(n *yaml.Node) error {
	if n.Kind == yaml.AliasNode || n.Anchor != "" {
		return errors.New("YAML aliases and anchors are not supported")
	}
	if n.Tag != "" && n.Tag != "!!map" && n.Tag != "!!seq" && n.Tag != "!!str" && n.Tag != "!!int" && n.Tag != "!!bool" && n.Tag != "!!null" {
		return errors.New("unsupported YAML tag")
	}
	if n.Kind == yaml.MappingNode {
		seen := map[string]bool{}
		for i := 0; i < len(n.Content); i += 2 {
			key := n.Content[i]
			if key.Kind != yaml.ScalarNode || key.Tag != "!!str" || key.Value == "<<" || seen[key.Value] {
				return errors.New("YAML mapping keys must be unique strings; merge keys are not supported")
			}
			seen[key.Value] = true
		}
	}
	for _, child := range n.Content {
		if err := validateYAML(child); err != nil {
			return err
		}
	}
	return nil
}

func (m manifest) body() []byte {
	value := struct {
		ProjectID string `json:"project_id"`
		poolSpec
	}{m.Metadata.ProjectID, m.Spec}
	data, _ := json.Marshal(value)
	return data
}

func newUUID() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		panic(err)
	}
	b[6] = (b[6] & 15) | 64
	b[8] = (b[8] & 63) | 128
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}
